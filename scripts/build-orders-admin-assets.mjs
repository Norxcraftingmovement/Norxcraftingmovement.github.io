// Bundles admin-ui/ (HTML, JS, CSS, Sarabun fonts, official logo) into one importable module so the
// admin Worker can serve them without Static Assets (which would drop Cloudflare Access identity).
import { readdirSync, readFileSync, writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";
import { join, extname } from "node:path";
const root = fileURLToPath(new URL("../admin-ui/", import.meta.url));
const types = { ".html": "text/html; charset=utf-8", ".css": "text/css; charset=utf-8", ".mjs": "text/javascript; charset=utf-8", ".woff2": "font/woff2", ".png": "image/png", ".txt": "text/plain; charset=utf-8" };
export function generate() {
  const files = [];
  for (const dir of ["", "fonts"]) for (const f of readdirSync(join(root, dir)).sort()) if (extname(f) in types) files.push([dir ? dir + "/" + f : f, join(root, dir, f)]);
  const assets = {};
  for (const [name, path] of files.sort(([a], [b]) => a.localeCompare(b))) {
    const buf = readFileSync(path), flat = name.replace(/^fonts\//, ""), type = types[extname(name)];
    assets[flat] = type.startsWith("text/") ? { type, text: buf.toString("utf8") } : { type, base64: buf.toString("base64") };
  }
  return "// GENERATED by scripts/build-orders-admin-assets.mjs from admin-ui/ — do not edit.\nexport const assets = " + JSON.stringify(assets, null, 1) + ";\n";
}
if (process.argv[1] === fileURLToPath(import.meta.url)) { writeFileSync(new URL("../src/generated/orders-admin-assets.mjs", import.meta.url), generate()); console.log("orders admin assets generated"); }
