import { readFileSync } from 'node:fs';
import { createHash } from 'node:crypto';
import { productThemeSources } from './product-theme-sources.mjs';
export function productPublicationAssetModule(){
  const {themes,fixtures}=productThemeSources(),read=p=>readFileSync(new URL('../'+p,import.meta.url),'utf8');
  const shared=read('admin-ui/product-template.mjs')+read('admin-ui/product-theme-options.mjs')+JSON.stringify(fixtures),extras=read('admin-ui/product-preview.css');
  for(const theme of Object.values(themes)){theme.css+='\n'+extras;theme.version=createHash('sha256').update(shared+theme.css).digest('hex');}
  return '// GENERATED by scripts/build-orders-admin-assets.mjs; no Admin UI or image bytes.\nexport const productSource = '+JSON.stringify({themes,fixtures})+';\n';
}
